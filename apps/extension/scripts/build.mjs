// Build the Chrome extension for this copy's web app (address from biblio.config.json).
// Source lives in apps/extension/src; everything Chrome loads is written to apps/extension/build
// (ignored by git), which is the one folder to "Load unpacked".
//   npm run build:extension   (also run by `npm run setup` and `npm run deploy`)
